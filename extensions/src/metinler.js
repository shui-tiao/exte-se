let DIL = "en";
const DESTEKLENEN_DILLER = new Set(Object.keys(METINLER));

/**
 * Etkin dili ayarlar. `kod`: desteklenen bir dil kodu veya "auto".
 * "auto" tarayıcı dilinin birincil alt etiketine bakar: zh-CN→zh, ja-JP→ja,
 * pt-BR→pt (desteklenmiyor) → en; böylece pt-BR yanlışlıkla es sayılmaz.
 */
export function diliAyarla(kod) {
  if (kod === "auto" || !kod) {
    const tarayici = globalThis.navigator?.language || "en";
    const birincil = tarayici.toLowerCase().split(/[-_]/)[0];
    DIL = DESTEKLENEN_DILLER.has(birincil) ? birincil : "en";
  } else {
    DIL = DESTEKLENEN_DILLER.has(kod) ? kod : "en";
  }
  return DIL;
}

export const etkinDil = () => DIL;

/** Anahtarı etkin dilde döndürür; `$1`, `$2`… yer tutucularını sırayla değiştirir. */
export function t(anahtar, ...ikame) {
  const metin = METINLER[DIL]?.[anahtar] ?? METINLER.en[anahtar] ?? anahtar;
  return ikame.length ? metin.replace(/\$(\d)/g, (_, n) => String(ikame[n - 1] ?? "")) : metin;
}
