let DIL = "en";

/** Etkin dili ayarlar. `kod`: "en" | "tr" | "zh" | "auto" (tarayıcı diline bakar). */
export function diliAyarla(kod) {
  if (kod === "auto" || !kod) {
    const tarayici = globalThis.navigator?.language || "en";
    const dilKodu = tarayici.toLowerCase();
    if (dilKodu.startsWith("zh")) DIL = "zh";
    else if (dilKodu.startsWith("tr")) DIL = "tr";
    else DIL = "en";
  } else {
    DIL = METINLER[kod] ? kod : "en";
  }
  return DIL;
}

export const etkinDil = () => DIL;

/** Anahtarı etkin dilde döndürür; `$1`, `$2`… yer tutucularını sırayla değiştirir. */
export function t(anahtar, ...ikame) {
  const metin = METINLER[DIL]?.[anahtar] ?? METINLER.en[anahtar] ?? anahtar;
  return ikame.length ? metin.replace(/\$(\d)/g, (_, n) => String(ikame[n - 1] ?? "")) : metin;
}
